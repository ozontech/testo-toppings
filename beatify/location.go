package beatify

import (
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"strings"

	"github.com/ozontech/testo"
	"github.com/ozontech/testo/testoreflect"
)

type sourceLoc struct {
	File string
	Line int
}

func testLocation(t *testo.T) sourceLoc {
	ref := testo.Reflect(t)

	if name := suiteMethodName(ref.Test); name != "" && ref.Suite.Value != nil {
		if loc := locFromSuiteMethod(ref.Suite.Value, name); loc.File != "" {
			return loc
		}
	}

	return locFromPC(funcPC(ref.Test))
}

func suiteMethodName(info testoreflect.TestInfo) string {
	switch v := info.(type) {
	case testoreflect.RegularTestInfo:
		if v.IsSubtest {
			return ""
		}

		return v.RawBaseName
	case testoreflect.ParametrizedTestInfo:
		return v.BaseName
	default:
		return ""
	}
}

func funcPC(info testoreflect.TestInfo) uintptr {
	switch v := info.(type) {
	case testoreflect.RegularTestInfo:
		return v.FuncPC
	case testoreflect.ParametrizedTestInfo:
		return v.FuncPC
	default:
		return 0
	}
}

func locFromSuiteMethod(suite any, name string) sourceLoc {
	typ := reflect.TypeOf(suite)
	if typ == nil {
		return sourceLoc{}
	}

	// Prefer the value type: pointer-method wrappers are often "<autogenerated>".
	if typ.Kind() == reflect.Pointer {
		typ = typ.Elem()
	}

	method, ok := typ.MethodByName(name)
	if !ok {
		return sourceLoc{}
	}

	return locFromPC(method.Func.Pointer())
}

func locFromPC(pc uintptr) sourceLoc {
	if pc == 0 {
		return sourceLoc{}
	}

	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return sourceLoc{}
	}

	file, line := fn.FileLine(pc)
	if !isRealFile(file) || line <= 0 {
		return sourceLoc{}
	}

	return sourceLoc{File: file, Line: line}
}

func isRealFile(file string) bool {
	return file != "" && file != "<autogenerated>"
}

func formatLocation(paint painter, loc sourceLoc) string {
	if loc.File == "" || loc.Line <= 0 {
		return paint.dim("-")
	}

	file := normalizePath(loc.File)
	text := fmt.Sprintf("%s:%d", shortPath(file), loc.Line)

	if !paint.enabled {
		// Absolute path:line is what IDE link detectors pick up most reliably.
		return fmt.Sprintf("%s:%d", file, loc.Line)
	}

	return osc8Link(editorURI(file, loc.Line), paint.cyan(text))
}

// normalizePath maps WSL /mnt/<drive>/... paths to Windows paths so
// editors on the host can open links from a WSL test run.
func normalizePath(abs string) string {
	const prefix = "/mnt/"

	if !strings.HasPrefix(abs, prefix) || len(abs) < len(prefix)+3 {
		return abs
	}

	drive := abs[len(prefix)]
	if abs[len(prefix)+1] != '/' {
		return abs
	}

	if drive < 'a' || drive > 'z' {
		if drive < 'A' || drive > 'Z' {
			return abs
		}
	}

	return strings.ToUpper(string(drive)) + ":" + abs[len(prefix)+1:]
}

func shortPath(abs string) string {
	cwd, err := os.Getwd()
	if err == nil {
		rel, relErr := filepath.Rel(cwd, abs)
		if relErr == nil && rel != "" && !strings.HasPrefix(rel, "..") {
			return filepath.ToSlash(rel)
		}
	}

	return filepath.ToSlash(filepath.Base(abs))
}

func editorURI(abs string, line int) string {
	// VS Code / Cursor file deep-link with line number.
	return fmt.Sprintf("vscode://file%s:%d", editorFilePath(abs), line)
}

func editorFilePath(abs string) string {
	abs = filepath.ToSlash(filepath.Clean(abs))

	// Windows drive paths (including WSL-normalized C:/...) need a leading slash:
	// vscode://file/C:/path/file.go:12
	if len(abs) >= 2 && abs[1] == ':' {
		return "/" + abs
	}

	return abs
}

func osc8Link(uri, text string) string {
	// OSC 8 ; params ; URI ST text OSC 8 ; ; ST
	return "\x1b]8;;" + uri + "\x1b\\" + text + "\x1b]8;;\x1b\\"
}
